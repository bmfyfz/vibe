// Writes migrations/index.ts: every migration, imported as text, in order.
//
// bun:sqlite has no `cf d1 migrations apply`, so the store applies migrations
// itself, and a compiled `vibe` binary has no migrations directory to read
// them from. Importing each file puts its SQL in the bundle. `bun db:generate`
// runs this after drizzle-kit, and a test fails when the two are out of step.
import { readdirSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "../migrations");

export function manifest(files: readonly string[]): string {
  const names = files.map((file) => file.replace(/\.sql$/, ""));
  return [
    "// Generated by `bun db:generate` from the files beside it. Do not edit.",
    ...names.map((name, n) => `import m${n} from "./${name}.sql" with { type: "text" };`),
    "",
    "/** Every migration, oldest first, with its SQL. */",
    "export const MIGRATIONS: readonly { name: string; sql: string }[] = [",
    ...names.map((name, n) => `  { name: "${name}", sql: m${n} },`),
    "];",
    "",
  ].join("\n");
}

export function migrationFiles(): string[] {
  return readdirSync(dir)
    .filter((file) => file.endsWith(".sql"))
    .sort();
}

if (import.meta.main) {
  await Bun.write(join(dir, "index.ts"), manifest(migrationFiles()));
  console.log(`Embedded ${migrationFiles().length} migrations in migrations/index.ts.`);
}
